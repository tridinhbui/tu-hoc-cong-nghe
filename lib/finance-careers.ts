// Curated "chân dung nghề nghiệp" (career profile) content for the /su-nghiep
// page - JD summary + required skills per finance career family, aimed at
// this app's audience (personal finance learners, professional/corporate +
// investment branches, CFA candidates).

export interface CareerTraits {
  analytical: number;   // Phân tích (1-5)
  compliance: number;   // Tuân thủ/Chính xác (1-5)
  clientFacing: number; // Giao tiếp/Khách hàng (1-5)
  quantitative: number; // Toán & Định lượng (1-5)
}

export interface FinanceCareer {
  id: string;
  title: string;
  englishTitle: string;
  emoji: string;
  accentFrom: string;
  accentTo: string;
  summary: string;
  responsibilities: string[];
  skills: string[];
  entryLevel: string;
  salaryHint: string;
  searchKeyword: string;
  // Real /bai-hoc/<slug> lesson slugs relevant to this career, verified
  // against lib/lessons-data/_index.json (or, for hand-coded static lesson
  // pages like "synergy-ma"/"source-cash-ma", against the actual build
  // output) - rendered as a "học các bài này để chuẩn bị" study plan on the
  // career detail view, and used to compute progress toward a tracked
  // career goal (see lib/supabase-career-goals.ts).
  relatedLessonSlugs: string[];
  // Cross-references CFA_LEVEL_1_SUBJECTS ids (lib/cfa-track.ts) this career
  // naturally draws on - rendered as "Liên quan CFA: ..." tags on the
  // detail view, tying the career map back to the CFA track's official
  // subject structure (not just individual lessons).
  relatedCfaSubjectIds?: string[];
  // Enhanced properties
  dayInLife: string;
  careerPath: string[];
  requiredTools: string[];
  certifications: string[];
  entryDifficulty: number; // 1-5 rating
  stressLevel: number; // 1-5 rating
  wlb: number; // 1-5 rating (Work-Life Balance)
  avatar3d: string; // path in public folder
  // Additional rich info
  pros: string;
  cons: string;
  applicationTips: string;
  // "data" là danh mục thứ năm, thêm sau bốn danh mục gốc. Mọi nơi hiển thị
  // theo danh mục phải liệt kê đủ cả năm, nếu không nghề thuộc danh mục thiếu
  // sẽ biến mất khỏi giao diện đó: components/CareerRoadmapMap.tsx,
  // components/CareerLearningPathClient.tsx và components/JobSearchClient.tsx.
  category: "investment" | "accounting" | "banking" | "advisory" | "data";
  traits: CareerTraits;
}

